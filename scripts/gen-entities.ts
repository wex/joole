/**
 * pnpm gen:entities — generates src/game/q2/q2.def and src/game/q2/models.ts
 * from id's GPL-licensed Quake 2 game code in ext/Quake-2/game (spec, Entity
 * definitions). Run this after cloning the source projects; ext/ is never in
 * Git, so the outputs are committed.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { parseQuakedBlocks } from '../src/core/formats/quaked';

const GAME_DIR = 'ext/Quake-2/game';
const Q2PRO_DIR = 'ext/q2pro/src/game';

function cFiles(dir: string): string[] {
  return readdirSync(dir)
    .filter((name) => name.endsWith('.c'))
    .map((name) => `${dir}/${name}`);
}

// --- q2.def: every QUAKED block verbatim, in file order --------------------

interface Block {
  readonly file: string;
  readonly text: string;
  readonly classNames: string[];
}

function extractBlocks(dir: string): Block[] {
  const blocks: Block[] = [];
  for (const path of cFiles(dir).sort()) {
    const text = readFileSync(path, 'utf8');
    let at = 0;
    for (;;) {
      const start = text.indexOf('/*QUAKED', at);
      if (start < 0) break;
      const end = text.indexOf('*/', start) + 2;
      const blockText = text.slice(start, end);
      const classNames = parseQuakedBlocks(blockText).map((def) => def.className);
      blocks.push({ file: path, text: blockText, classNames });
      at = end;
    }
  }
  return blocks;
}

const blocks = extractBlocks(GAME_DIR);
const totalClasses = blocks.reduce((n, block) => n + block.classNames.length, 0);
console.log(`extracted ${blocks.length} QUAKED blocks, ${totalClasses} classes`);

// Comparison with q2pro's game code: report classes only in one source.
if (readdirSync('ext/q2pro/src', { withFileTypes: false }).length > 0) {
  try {
    const proBlocks = extractBlocks(Q2PRO_DIR);
    const vanilla = new Set(blocks.flatMap((block) => block.classNames));
    const pro = new Set(proBlocks.flatMap((block) => block.classNames));
    const onlyVanilla = [...vanilla].filter((name) => !pro.has(name));
    const onlyPro = [...pro].filter((name) => !vanilla.has(name));
    console.log(
      `q2pro comparison: ${proBlocks.length} blocks; only in vanilla: [${onlyVanilla.join(', ')}]; only in q2pro: [${onlyPro.join(', ')}]`,
    );
  } catch {
    console.log('q2pro game sources not found, comparison skipped');
  }
}

const defHeader = `// Quake 2 entity definitions, generated by pnpm gen:entities on ${new Date().toISOString().slice(0, 10)}.
// The /*QUAKED*/ blocks are copied verbatim from id's GPL-licensed game code
// (release 3.21, https://github.com/id-Software/Quake-2, ext/Quake-2/game/*.c).
// Regenerate with pnpm gen:entities; do not edit by hand.

`;
writeFileSync(
  'src/game/q2/q2.def',
  defHeader + blocks.map((block) => block.text).join('\n\n') + '\n',
);

// --- models.ts: class-to-model table from the spawn functions --------------

/** The model paths of a function body: the entity's own model first. */
function modelsOfBody(body: string): string[] {
  const out: string[] = [];
  const own = /self->s\.modelindex\s*=\s*gi\.modelindex\s*\(\s*"([^"]+)"/g;
  for (const m of body.matchAll(own)) out.push(m[1]!);
  const setmodel = /gi\.setmodel\s*\(\s*(?:self|ent)\s*,\s*"([^"]+)"/g;
  for (const m of body.matchAll(setmodel)) out.push(m[1]!);
  const direct = /(?:self|ent)->model\s*=\s*"(models\/[^"]+)"/g;
  for (const m of body.matchAll(direct)) out.push(m[1]!);
  return [...new Set(out)];
}

/**
 * The models of a spawn function, following the shared SP_ helper functions
 * it calls (monster code initialises the model in SP_<x>_x helpers) and the
 * SpawnItem helper used by every item.
 */
function modelsOfSpawn(sources: string, className: string, depth = 0): string[] {
  const body = spawnBody(sources, className);
  if (!body) return [];
  const own = modelsOfBody(body);
  if (own.length > 0 || depth >= 2) return own;
  const helpers = [...body.matchAll(/\bSP_(\w+)\s*\(/g)].map((m) => m[1]!);
  const seen = new Set<string>();
  for (const helper of helpers) {
    if (helper === className || seen.has(helper)) continue;
    seen.add(helper);
    const found = modelsOfSpawn(sources, helper, depth + 1);
    if (found.length > 0) return found;
  }
  return [];
}

/** The body text of `void SP_name(...)`, up to the next top-level function. */
function spawnBody(sources: string, name: string): string | null {
  const start = sources.search(new RegExp(`\\nvoid\\s+SP_${name}\\s*\\([^)]*\\)\\s*\\n\\{`));
  if (start < 0) return null;
  const brace = sources.indexOf('{', start);
  if (brace < 0) return null;
  let depth = 0;
  for (let i = brace; i < sources.length; i++) {
    if (sources[i] === '{') depth++;
    if (sources[i] === '}') {
      depth--;
      if (depth === 0) return sources.slice(brace, i + 1);
    }
  }
  return null;
}

const allSources = cFiles(GAME_DIR)
  .sort()
  .map((path) => readFileSync(path, 'utf8'))
  .join('\n');

// Classes whose model is set in a shared helper instead of their own spawn
// function, or which need a hand-picked representative model.
const MANUAL_OVERRIDES: Record<string, string> = {};

// The itemlist in g_items.c carries every item's world model as a struct
// field (gitem_t.world_model). Most items have no spawn function of their
// own, so this is the primary source for item_* classes.
const itemModels = new Map<string, string>();
{
  const items = readFileSync('ext/Quake-2/game/g_items.c', 'utf8');
  const tableStart = items.indexOf('itemlist[]');
  if (tableStart >= 0) {
    const region = items.slice(tableStart);
    // Each entry is a brace-delimited struct initialiser.
    for (const entry of region.split(/\n\t\},/)) {
      const cls = /\{\s*"((?:item|key|weapon|ammo)_\w+)"/.exec(entry);
      const model = /"(models\/[^"]+)"/.exec(entry);
      if (cls && model) itemModels.set(cls[1]!, model[1]!);
    }
  }
}
console.log(`itemlist: ${itemModels.size} item models`);

const modelTable = new Map<string, string>();
for (const block of blocks) {
  for (const className of block.classNames) {
    if (MANUAL_OVERRIDES[className]) {
      modelTable.set(className, MANUAL_OVERRIDES[className]);
      continue;
    }
    if (itemModels.has(className)) {
      modelTable.set(className, itemModels.get(className)!);
      continue;
    }
    const models = modelsOfSpawn(allSources, className).filter((path) =>
      path.startsWith('models/'),
    );
    if (models.length > 0) modelTable.set(className, models[0]!);
  }
}

const entries = [...modelTable.entries()].sort(([a], [b]) => a.localeCompare(b));
console.log(`model table: ${entries.length} classes with models`);
const modelsTs = `// Class-to-model table, generated by pnpm gen:entities on ${new Date().toISOString().slice(0, 10)}.
// Compiled from the gi.modelindex and gi.setmodel calls of the spawn functions
// in id's GPL-licensed game code (ext/Quake-2/game), plus manual overrides for
// classes whose model is set in a shared helper. Regenerate with
// pnpm gen:entities; do not edit by hand.

/** The md2 model path of an entity class, when it has one. */
export const CLASS_MODELS: Readonly<Record<string, string>> = {
${entries.map(([name, model]) => `  ${JSON.stringify(name)}: ${JSON.stringify(model)},`).join('\n')}
};
`;
writeFileSync('src/game/q2/models.ts', modelsTs);
console.log('wrote src/game/q2/q2.def and src/game/q2/models.ts');
